    public static extern IntPtr GetForegroundWindow();

    [DllImport("user32.dll")]
    public static extern uint GetWindowThreadProcessId(IntPtr hwnd, out uint processId);

    [DllImport("kernel32.dll")]
    public static extern uint GetCurrentProcessId();

    /// <summary>
    /// True when the foreground window belongs to this app. The overlay sits on top
    /// of everything, so when one of our own windows (the tray flyout) is active we
    /// must not shove the overlay back over it.
    /// </summary>
    public static bool OwnWindowIsForeground(IntPtr exceptHandle)
    {
        var foreground = GetForegroundWindow();
        if (foreground == IntPtr.Zero || foreground == exceptHandle) return false;
        GetWindowThreadProcessId(foreground, out var processId);
        return processId == GetCurrentProcessId();
    }
}
